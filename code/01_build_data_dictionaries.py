"""Fetch the official Census variable metadata for every ACS table referenced
in code/sovi_variables.py and save it as a merged CSV data dictionary per
vintage in documentation/data_dictionaries/.

This is the authoritative record of what each ACS variable code means. It is
regenerated by querying the live Census API metadata endpoint for each table
(https://api.census.gov/data/<vintage>/acs/acs5/groups/<table>.json) rather
than hand-maintained, so it can be re-run if the vintages in
code/census_config.py change.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))  # find census_config.py when not run from code/

import pandas as pd
import requests

from census_config import DATASET, YEARS

OUTPUT_DIR = Path("documentation/data_dictionaries")

# Every ACS table referenced by SOVI_VARIABLES / HOUSING_COST_BURDEN_CODES in
# sovi_variables.py.
TABLES = [
    "B01001", "B01002", "B02001", "B03003", "B09002", "B11001", "B15003",
    "B17001", "B19001", "B19055", "B19301", "B23001", "B23025",
    "B25001", "B25002", "B25003", "B25024", "B25044", "B25064", "B25070",
    "B25077", "B25091", "B27001", "C16002", "C24010", "C24030",
]


def fetch_table(year, table):
    url = f"https://api.census.gov/data/{year}/{DATASET}/groups/{table}.json"
    resp = requests.get(url, timeout=30)
    assert resp.status_code == 200, f"{table}: HTTP {resp.status_code} from {url}"
    variables = resp.json()["variables"]
    rows = [
        {"table": table, "variable": code, "label": meta["label"], "concept": meta.get("concept")}
        for code, meta in variables.items()
        if code.endswith("E") and not code.endswith(("EA", "MA")) and code != "NAME"
    ]
    rows.sort(key=lambda r: r["variable"])
    return pd.DataFrame(rows)


def build_dictionary(year):
    tables = {table: fetch_table(year, table) for table in TABLES}

    column_sets = {tuple(df.columns) for df in tables.values()}
    assert len(column_sets) == 1, (
        f"Tables returned different columns ({column_sets}); "
        "writing per-table files instead of merging so nothing is silently dropped."
    )

    return pd.concat(tables.values(), ignore_index=True)


def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    for year in YEARS:
        merged = build_dictionary(year)
        merged_path = OUTPUT_DIR / f"acs_variable_dictionary_{year}.csv"
        merged.to_csv(merged_path, index=False)
        print(f"wrote {merged_path} ({len(merged)} variables across {len(TABLES)} tables)")


if __name__ == "__main__":
    main()
